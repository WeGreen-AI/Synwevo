export type Workspace = { id: string; name: string; role: string };
export type Member = { id: string; display_name: string; role: string };
export type Page<T> = { items: T[]; total: number; next_offset: number | null };
export type Selector = { users: string[]; min_role?: string | null };
export type Rule = { field: string; op: string; value?: string | string[] | null };
export type Field = { id: string; label: string; type: string; required: boolean; help?: string;
  currency?: string | null; decimals?: number | null; min?: string | null; max?: string | null;
  max_length?: number | null; options: { value: string; label: string }[] };
export type Stage = { id: string; name: string; approvers: Selector; mode: string; required?: number | null;
  condition?: { match: string; rules: Rule[] } | null;
  due?: { hours: number; remind: boolean; escalation?: { after_hours: number; action: string; approvers: Selector } | null } | null };
export type Definition = { fields: Field[]; stages: Stage[]; rules: { distinct_deciders: boolean } };
export type Template = { id: string; title: string; description: string; status: string; draft: Definition; draft_rev: number;
  published_version: number | null; problems: { code: string; message: string; stage?: string; field?: string }[];
  warnings: { code: string; message: string; stage: string; users: string[] }[];
  versions: { version: number; title: string; status: string; published_at: number; note: string }[] };
export type Snapshot = { revision: number; fields: Record<string, string>; basis: string; fields_hash: string; basis_hash: string;
  note: string; submitted_at: number; submitted_by: string };
export type RequestRow = { id: string; title: string; status: string; revision: number; state_version: number; updated_at: number };
export type ApprovalRequest = RequestRow & { template_id: string; template_version: number; requester_id: string;
  definition: Definition; snapshot: Snapshot; previous: Snapshot | null; people: Record<string, string>;
  revisions: Omit<Snapshot, "fields" | "basis">[];
  stages: { id: string; stage_name: string; mode: string; required: number; status: string; due_at: number | null; reminded_at: number | null; escalated_at: number | null; skip: Rule[] }[];
  tasks: { id: string; assignee_id: string; status: string; eligible: boolean; source: string }[];
  permissions: { requester: boolean; manage: boolean; task_ids: string[] };
  decisions: { id: string; decider_id: string; decision: string; revision: number; created_at: number }[] };
export type Timeline = { seq: number; actor_id: string | null; actor_name?: string; at: number; kind: string; revision: number;
  detail: { note?: string; decision?: string; action?: string; stage_id?: string; required?: number; to_user_id?: string;
    checks?: { label: string; op: string; actual: unknown; value: unknown; result: boolean }[] } };
