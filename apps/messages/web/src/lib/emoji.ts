export const RECENT_KEY = "synwevo.msg.emoji.recent";
export const RECENT_MAX = 24;

export function readRecent(storage: Pick<Storage, "getItem"> | null): string[] {
  try {
    const raw = storage?.getItem(RECENT_KEY);
    const list = raw ? JSON.parse(raw) : [];
    return Array.isArray(list) ? list.filter((x): x is string => typeof x === "string").slice(0, RECENT_MAX) : [];
  } catch { return []; }
}

/** The list with `emoji` moved to the front, capped. Pure so the storage write is the caller's. */
export function pushRecent(list: string[], emoji: string): string[] {
  return [emoji, ...list.filter(e => e !== emoji)].slice(0, RECENT_MAX);
}
