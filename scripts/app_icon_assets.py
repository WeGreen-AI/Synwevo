#!/usr/bin/env python3
"""Verify the supplied PNG originals and derive only registered application/entry icons.

The registry uses real app IDs or existing account module paths, not packaging asset keys.
Keep the full transparent canvas: no alpha threshold, crop, recolouring or upscaling.
Like brand_assets.py, resize on premultiplied alpha with Pillow/Lanczos. Optical adjustments
live in registry.json and are applied by AppIcon, not baked into the preserved source pixels.
Run from any directory; --check rebuilds in memory without changing files.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "packages/ui/app-icons"
WEB = ROOT / "packages/ui/src/app-icons"


def outputs() -> dict[Path, bytes]:
    manifest = json.loads((ASSETS / "source-manifest.json").read_text())
    sources = {}
    assert manifest["count"] == len(manifest["icons"]) == 12
    for item in manifest["icons"]:
        path = ASSETS / "originals" / item["source_file"]
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == item["sha256"], path
        assert len(raw) == item["size_bytes"], path
        im = Image.open(io.BytesIO(raw))
        assert im.format == "PNG" and im.mode == "RGBA" and im.size == (1254, 1254), path
        assert im.getchannel("A").getextrema() == (0, 255), path
        sources[item["asset_key"]] = (im, item)
    registry = json.loads((ASSETS / "registry.json").read_text())
    result: dict[Path, bytes] = {}
    imports, entries, provenance = [], [], []
    for identity, spec in registry.items():
        im, source = sources[spec["asset"]]
        files = []
        for side in spec["sizes"]:
            assert side <= im.width
            filename = f"synwevo-{spec['asset']}-{side}.png"
            variable = f"{spec['asset']}_{side}"
            resized = im.convert("RGBa").resize((side, side), Image.Resampling.LANCZOS).convert("RGBA")
            buf = io.BytesIO()
            resized.save(buf, format="PNG", optimize=True)
            raw = buf.getvalue()
            result[WEB / filename] = raw
            imports.append(f'import {variable} from "./{filename}?no-inline";')
            files.append(f"{{ src: {variable}, width: {side} }}")
            provenance.append({"id": identity, "source": source["source_file"],
                               "source_sha256": source["sha256"], "file": filename,
                               "width": side, "height": side, "bytes": len(raw),
                               "sha256": hashlib.sha256(raw).hexdigest()})
        entries.append(f'  {json.dumps(identity)}: {{ scale: {spec["scale"]}, x: {spec["x"]}, y: {spec["y"]}, files: [{", ".join(files)}] }},')
    code = '\n'.join([
        "// Generated by scripts/app_icon_assets.py. Edit app-icons/registry.json, not this file.",
        "// Vite emits fingerprinted URLs (including configured base/CDN); never inline these images.",
        *imports, "", "export const APP_ICON_ASSETS = {", *entries, "} as const;", "",
        "export type AppIconId = keyof typeof APP_ICON_ASSETS;", "",
        "export function appIconAsset(id: string | null | undefined) {",
        "  return id && Object.prototype.hasOwnProperty.call(APP_ICON_ASSETS, id)",
        "    ? APP_ICON_ASSETS[id as AppIconId] : null;", "}", "",
    ])
    result[WEB / "assets.ts"] = code.encode()
    result[ASSETS / "derived-manifest.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    return result


#: Largest per-channel difference `--check` accepts, as brand_assets.py: resampling is pinned to one
#: Pillow version, but the PNG encoder's bytes and a CPU's vector rounding differ between machines
#: (the CI image is not this laptop); a stale, hand-edited or re-drawn file differs by far more.
TOLERANCE = 2


def same_pixels(a: bytes, b: bytes) -> bool:
    x, y = (Image.open(io.BytesIO(data)).convert("RGBA") for data in (a, b))
    if x.size != y.size:
        return False
    return max(hi for _, hi in ImageChops.difference(x, y).getextrema()) <= TOLERANCE


def without_encoder_fields(manifest: bytes) -> list:
    """The provenance record minus what depends on the PNG encoder (output bytes and hash)."""
    return [{k: v for k, v in entry.items() if k not in ("bytes", "sha256")} for entry in json.loads(manifest)]


def same_output(path: Path, raw: bytes) -> bool:
    if not path.is_file():
        return False
    committed = path.read_bytes()
    if path.suffix == ".png":
        return same_pixels(committed, raw)
    if path.name == "derived-manifest.json":
        return without_encoder_fields(committed) == without_encoder_fields(raw)
    return committed == raw


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    built = outputs()
    for path, raw in built.items():
        if check:
            assert same_output(path, raw), f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    expected = {p for p in built if p.suffix == ".png"}
    assert set(WEB.glob("*.png")) == expected, "Unexpected unused derived PNG"
    print(f"12 original PNGs verified; {len(expected)} renditions {'checked' if check else 'generated'} "
          f"({sum(len(built[p]) for p in expected):,} bytes total).")


if __name__ == "__main__":
    main()
