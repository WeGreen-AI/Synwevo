#!/usr/bin/env python3
"""Derive every Synwevo logo file the product uses from the confirmed originals.

The three confirmed logo images are kept unchanged in `packages/ui/brand/originals/`:

    synwevo-logo-full.png      full lockup: the woven S mark and the Synwevo wordmark
    synwevo-logo-mark.png      the mark alone
    synwevo-logo-wordmark.webp the wordmark alone

They are not pixel-identical to one another. Scaled to the same size, the standalone mark overlaps
the lockup's mark by only ~0.83 (IoU) — the inner cut and the lower hook sit elsewhere — and the
standalone wordmark overlaps the lockup's wordmark by ~0.78, with different letter spacing. The
full lockup is the reference, so the mark and the wordmark shown in the product are **cut out of the
lockup's own pixels**: a crop, never a redraw, a re-typeset word or a traced outline. The two
standalone originals are kept as the confirmed record; nothing is derived from them.

What this script may do to pixels, and nothing else:
  * crop to the ink plus a few pixels of the original's own antialiased margin;
  * resample proportionally (Lanczos on premultiplied alpha, so edges keep their antialiasing);
  * place the mark on an icon tile (browser and home-screen icons need a defined background:
    iOS fills transparency with black, and a near-black mark disappears on a dark tab strip);
  * recolour the foreground to white for dark backgrounds, keeping alpha — outline, letterforms
    and antialiasing stay exactly as they are.

Everything is raster. There is no SVG here, because a bitmap wrapped in an SVG is not a vector.

Outputs (all regenerated by this script; never edit them by hand):
  packages/ui/src/brand/        renditions, icon links and assets.ts, imported by the shells (Vite fingerprints them)
  packages/ui/public-brand/     favicon.ico, copied to each shell's root for requests that name no icon
  packages/ui/brand/derived/    full-resolution crops (and white versions) for non-web uses
  packages/ui/brand/assets.json provenance: source hash, crop box, size and hash of every output

Usage:
  python scripts/brand_assets.py           write every output
  python scripts/brand_assets.py --check   rebuild in memory, fail if a committed file differs
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "packages/ui/brand"
ORIGINALS = BRAND / "originals"
WEB = ROOT / "packages/ui/src/brand"
PUBLIC = ROOT / "packages/ui/public-brand"
DERIVED = BRAND / "derived"
MANIFEST = BRAND / "assets.json"

REFERENCE = ORIGINALS / "synwevo-logo-full.png"
CONFIRMED = {
    "full": ORIGINALS / "synwevo-logo-full.png",
    "mark": ORIGINALS / "synwevo-logo-mark.png",
    "wordmark": ORIGINALS / "synwevo-logo-wordmark.webp",
}

#: Alpha at or below this is the background-removal haze around the artwork, not ink. It decides
#: where the ink ends; the haze pixels that fall inside the kept margin are copied unchanged.
NOISE = 8
#: Columns of the lockup with no ink wider than this separate the mark from the wordmark.
MIN_GAP = 20
#: Original pixels kept around the ink so the antialiased edge is never clipped.
PAD = 4

#: Rendition heights in device pixels. The Brand component shows the lockup and the mark at
#: 24–32 CSS px and the wordmark at 14–18 CSS px; each ladder covers 1×–3× screens without
#: upscaling past the source (lockup ink 321 px tall, wordmark 238 px, mark 321 px).
LADDERS = {
    "full": (32, 64, 128),
    "mark": (32, 64, 128),
    "wordmark": (24, 48, 96),
}

#: Browser tab icon: the mark on a white rounded tile. Tab strips are light or dark depending on
#: the browser theme, and support for switching favicons by colour scheme is inconsistent, so the
#: tile keeps the near-black mark legible on both.
FAVICON_SIZES = (16, 32, 48)
FAVICON_MARK = 0.80          # share of the tile the mark's longer side may occupy
FAVICON_RADIUS = 0.22        # corner radius as a share of the tile
#: Home-screen icon: opaque square (iOS masks the corners itself) with the mark inside the
#: centre safe area.
TOUCH_SIZE = 180
TOUCH_MARK = 0.62
TILE = (255, 255, 255, 255)
WHITE = (255, 255, 255)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def ink_bbox(im: Image.Image) -> tuple[int, int, int, int]:
    box = im.getchannel("A").point(lambda v: 255 if v > NOISE else 0).getbbox()
    if box is None:
        raise SystemExit("no ink found in the reference lockup")
    return box


def split_lockup(im: Image.Image) -> dict[str, tuple[int, int, int, int]]:
    """Crop boxes (in lockup coordinates) for the mark, the wordmark and the whole lockup."""
    alpha = im.getchannel("A").point(lambda v: 255 if v > NOISE else 0)
    w, h = im.size
    cols = [alpha.crop((x, 0, x + 1, h)).getbbox() is not None for x in range(w)]
    groups: list[list[int]] = []
    for x, has_ink in enumerate(cols):
        if not has_ink:
            continue
        if groups and x - groups[-1][1] <= MIN_GAP:
            groups[-1][1] = x
        else:
            groups.append([x, x])
    if len(groups) != 2:
        raise SystemExit(f"expected the lockup to have two ink groups (mark, wordmark), found {len(groups)}")

    def padded(x0: int, x1: int) -> tuple[int, int, int, int]:
        region = alpha.crop((x0, 0, x1 + 1, h))
        bx0, by0, bx1, by1 = region.getbbox()
        return (max(0, x0 + bx0 - PAD), max(0, by0 - PAD), min(w, x0 + bx1 + PAD), min(h, by1 + PAD))

    mark = padded(*groups[0])
    word = padded(*groups[1])
    full = (min(mark[0], word[0]), min(mark[1], word[1]), max(mark[2], word[2]), max(mark[3], word[3]))
    return {"full": full, "mark": mark, "wordmark": word}


def resample(im: Image.Image, size: tuple[int, int]) -> Image.Image:
    """Proportional Lanczos resample on premultiplied alpha (no dark or light fringes)."""
    return im.convert("RGBa").resize(size, Image.LANCZOS).convert("RGBA")


def to_height(im: Image.Image, height: int) -> Image.Image:
    width = max(1, round(im.width * height / im.height))
    return resample(im, (width, height))


def whiten(im: Image.Image) -> Image.Image:
    """Single-colour white version for dark backgrounds: RGB replaced, alpha untouched."""
    out = Image.new("RGBA", im.size, WHITE + (0,))
    out.putalpha(im.getchannel("A"))
    return out


def fit_into(im: Image.Image, box: int) -> Image.Image:
    scale = box / max(im.size)
    return resample(im, (max(1, round(im.width * scale)), max(1, round(im.height * scale))))


def tile(size: int, radius: float) -> Image.Image:
    """An antialiased rounded square, drawn at 8× and reduced."""
    big = size * 8
    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(layer).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(big * radius), fill=TILE)
    return resample(layer, (size, size))


def icon(mark: Image.Image, size: int, share: float, radius: float | None) -> Image.Image:
    base = tile(size, radius) if radius is not None else Image.new("RGBA", (size, size), TILE)
    glyph = fit_into(mark, round(size * share))
    base.alpha_composite(glyph, ((size - glyph.width) // 2, (size - glyph.height) // 2))
    return base if radius is not None else base.convert("RGB")


def png_bytes(im: Image.Image) -> bytes:
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def ico_bytes(images: list[Image.Image]) -> bytes:
    buf = io.BytesIO()
    largest = images[-1]
    largest.save(buf, "ICO", sizes=[im.size for im in images], append_images=images[:-1])
    return buf.getvalue()


def typescript_module(renditions: dict[str, list[tuple[str, tuple[int, int]]]],
                      masters: dict[str, tuple[int, int]]) -> bytes:
    """The module the Brand component imports: every rendition with its real pixel size."""
    lines = ["// Generated by scripts/brand_assets.py from packages/ui/brand/originals/. Do not edit.",
             "// Vite fingerprints each file; renditions under its inline limit become data: URIs.", ""]
    names: dict[str, str] = {}
    for version, items in renditions.items():
        for filename, _ in items:
            ident = filename.removesuffix(".png").replace("synwevo-logo-", "").replace("-", "_")
            names[filename] = ident
            lines.append(f'import {ident} from "./{filename}";')
    lines += ["", "export type LogoVersion = " + " | ".join(f'"{v}"' for v in renditions) + ";",
              "export type LogoFile = { src: string; width: number; height: number };", "",
              "/** Width ÷ height of each version, from the full-resolution crop of the lockup. */",
              "export const LOGO_ASPECT: Record<LogoVersion, number> = {"]
    lines += [f"  {v}: {w} / {h}," for v, (w, h) in masters.items()]
    lines += ["};", "", "/** Renditions of each version, smallest first. */",
              "export const LOGO_FILES: Record<LogoVersion, readonly LogoFile[]> = {"]
    for version, items in renditions.items():
        entries = ", ".join(f"{{ src: {names[f]}, width: {w}, height: {h} }}" for f, (w, h) in items)
        lines.append(f"  {version}: [{entries}],")
    lines += ["};", ""]
    return "\n".join(lines).encode()


def pixels(data: bytes) -> list[tuple[tuple[int, int], bytes]]:
    """Decoded frames of a PNG or ICO, for comparisons that ignore encoder differences."""
    im = Image.open(io.BytesIO(data))
    if im.format == "ICO":
        return [(s, im.ico.getimage(s).convert("RGBA").tobytes()) for s in sorted(im.ico.sizes())]
    return [(im.size, im.convert("RGBA").tobytes())]


def build() -> tuple[dict[Path, bytes], dict]:
    lockup = Image.open(REFERENCE)
    lockup.load()
    lockup = lockup.convert("RGBA")
    boxes = split_lockup(lockup)
    crops = {name: lockup.crop(box) for name, box in boxes.items()}

    files: dict[Path, bytes] = {}
    records: list[dict] = []
    renditions: dict[str, list[tuple[str, tuple[int, int]]]] = {name: [] for name in crops}

    def emit(path: Path, data: bytes, kind: str, derived_from: str, steps: list[str], size) -> None:
        files[path] = data
        records.append({
            "path": path.relative_to(ROOT).as_posix(), "kind": kind, "size": list(size),
            "sha256": sha256(data), "derived_from": derived_from, "steps": steps,
        })

    ref = REFERENCE.relative_to(ROOT).as_posix()
    for name, crop in crops.items():
        box = list(boxes[name])
        step_crop = f"crop {box} from the lockup (ink alpha > {NOISE}, {PAD}px original margin)"
        emit(DERIVED / f"synwevo-logo-{name}.png", png_bytes(crop), name, ref, [step_crop], crop.size)
        emit(DERIVED / f"synwevo-logo-{name}-white.png", png_bytes(whiten(crop)), name + "-white", ref,
             [step_crop, "foreground recoloured to white, alpha unchanged"], crop.size)
        for height in LADDERS[name]:
            scaled = to_height(crop, height)
            steps = [step_crop, f"Lanczos to {height}px tall (premultiplied alpha)"]
            emit(WEB / f"synwevo-logo-{name}-{height}.png", png_bytes(scaled), name, ref, steps, scaled.size)
            renditions[name].append((f"synwevo-logo-{name}-{height}.png", scaled.size))

    mark = crops["mark"]
    mark_step = f"crop {list(boxes['mark'])} from the lockup"
    favicons = [icon(mark, s, FAVICON_MARK, FAVICON_RADIUS) for s in FAVICON_SIZES]
    emit(PUBLIC / "favicon.ico", ico_bytes(favicons), "favicon", ref,
         [mark_step, f"mark fitted to {int(FAVICON_MARK * 100)}% of a white rounded tile, sizes {list(FAVICON_SIZES)}"],
         (FAVICON_SIZES[-1], FAVICON_SIZES[-1]))
    fav32 = favicons[FAVICON_SIZES.index(32)]
    emit(WEB / "icon-32.png", png_bytes(fav32), "favicon", ref,
         [mark_step, f"mark fitted to {int(FAVICON_MARK * 100)}% of a white rounded 32px tile"], fav32.size)
    touch = icon(mark, TOUCH_SIZE, TOUCH_MARK, None)
    emit(WEB / "apple-touch-icon.png", png_bytes(touch), "apple-touch-icon", ref,
         [mark_step, f"mark fitted to {int(TOUCH_MARK * 100)}% of an opaque white {TOUCH_SIZE}px square"], touch.size)

    files[WEB / "assets.ts"] = typescript_module(renditions, {n: c.size for n, c in crops.items()})

    manifest = {
        "about": "Generated by scripts/brand_assets.py from the confirmed originals. Do not edit by hand.",
        "reference": ref,
        "originals": [
            {"version": v, "path": p.relative_to(ROOT).as_posix(), "sha256": sha256(p.read_bytes()),
             "size": list(Image.open(p).size), "used_for_derivation": p == REFERENCE}
            for v, p in CONFIRMED.items()
        ],
        "why_the_lockup_is_the_source": (
            "The standalone mark and wordmark differ from the lockup in outline and letter spacing; "
            "the mark and the wordmark in the product are cropped from the lockup's own pixels."),
        "crop_boxes": {k: list(v) for k, v in boxes.items()},
        "outputs": sorted(records, key=lambda r: r["path"]),
    }
    return files, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed output is missing or differs")
    args = parser.parse_args()
    for p in CONFIRMED.values():
        if not p.is_file():
            print(f"missing confirmed original: {p.relative_to(ROOT)}", file=sys.stderr)
            return 2
    files, manifest = build()
    manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()

    if args.check:
        stale = []
        for path, data in files.items():
            same = path.is_file() and (path.read_bytes() == data if path.suffix == ".ts"
                                       else pixels(path.read_bytes()) == pixels(data))
            if not same:
                stale.append(path.relative_to(ROOT).as_posix())
        expected = {p.resolve() for p in files}
        for folder in (WEB, PUBLIC, DERIVED):
            for p in folder.glob("*"):
                if p.is_file() and p.resolve() not in expected:
                    stale.append(f"{p.relative_to(ROOT).as_posix()} (not produced by this script)")
        if stale:
            print("Logo files out of date — run python scripts/brand_assets.py:\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print(f"✓ {len(files)} logo files match the confirmed originals")
        return 0

    for folder in (WEB, PUBLIC, DERIVED):
        folder.mkdir(parents=True, exist_ok=True)
        for p in [*folder.glob("*.png"), *folder.glob("*.ico")]:
            if p not in files:
                p.unlink()
    for path, data in files.items():
        path.write_bytes(data)
    MANIFEST.write_bytes(manifest_bytes)
    total = sum(len(d) for d in files.values())
    print(f"wrote {len(files)} files ({total / 1024:.0f} KiB) and {MANIFEST.relative_to(ROOT)}")
    for rec in manifest["outputs"]:
        print(f"  {rec['path']:<58} {rec['size'][0]:>5}×{rec['size'][1]:<4} {rec['kind']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
